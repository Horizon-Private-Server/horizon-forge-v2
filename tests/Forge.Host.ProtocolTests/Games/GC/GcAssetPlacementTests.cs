internal static class GcAssetPlacementTests
{
    public static async Task RunAsync()
    {
        var root = Path.Combine(Path.GetTempPath(), $"forge-converted-placement-{Guid.NewGuid():N}");
        try
        {
            var catalog = await AssetCatalogStore.OpenAsync(Path.Combine(root, "catalog"));
            var sources = new List<AssetCatalogEntry>();
            foreach (var kind in new[] { AssetKind.Tie, AssetKind.Shrub, AssetKind.Moby })
            {
                var model = kind switch
                {
                    // Generated by the SDK's GcTieSplitConversionTests.Fixture; contains no retail data.
                    AssetKind.Tie => File.ReadAllBytes(Path.Combine(AppContext.BaseDirectory, "fixtures", "gc-folded-tie.bin")),
                    AssetKind.Shrub => new byte[0xc0],
                    _ => MobyModelPacker.Build(new() { Scale = 1 }),
                };
                var palette = new byte[0x400];
                palette[0] = palette[1] = palette[2] = 255; palette[3] = 128;
                IReadOnlyList<FrontendAssetTexture> textures = kind == AssetKind.Tie
                    ? [new(0, PifWriter.Write(PifWriter.CreateIndexed8(32, 32, palette, new byte[1024])))] : [];
                var bytes = CatalogModelCodec.Encode(GameId.GC, new byte[kind == AssetKind.Shrub ? 0x30 : 0x20], model, textures);
                sources.Add(await catalog.PutAsync(kind, 1, bytes, Metadata(kind)));
            }
            foreach (var entry in sources)
            {
                var unsupported = entry with { Sources = [entry.Sources[0] with { Revision = "1.00" }] };
                Check(!UyaAssetPlacementService.PlacementCompatibility(unsupported, "NTSC-U", "1.00", [0x1234], true).CanPlace,
                    "GC conversion rejects unsupported source revisions");
            }
            var sky = sources[0] with { Kind = AssetKind.Sky, CanonicalFormatVersion = 0 };
            Check(UyaSkyShellEditorService.PlacementCompatibility(sky, "NTSC-U", "1.00", true, 0, 0).CanPlace,
                "GC 1.01 skies are convertible");
            Check(!UyaSkyShellEditorService.PlacementCompatibility(sky, "PAL", "1.00", true, 0, 0).CanPlace,
                "GC sky conversion rejects unsupported targets");
            var retained = UyaCustomTieClassRegistry.AllocateConverted(ProjectCustomClassRegistry.Empty,
                AssetKind.Tie, sources[0].Id, 0x00c6, new HashSet<int> { 0x9000 }, preserveSourceClassId: true);
            Check(retained.Allocations.Single().ClassId == 0x00c6, "GC ties retain their native class ID");
            UyaCustomTieClassRegistry.Validate(retained);
            try
            {
                UyaCustomTieClassRegistry.AllocateConverted(ProjectCustomClassRegistry.Empty,
                    AssetKind.Tie, sources[0].Id, 0x00c6, new HashSet<int> { 0x00c6 }, preserveSourceClassId: true);
                throw new Exception("Expected GC class conflict");
            }
            catch (InvalidDataException error) { Check(error.Message.Contains("conflicts"), "occupied GC class is reported"); }
            var projectPath = Path.Combine(root, "project");
            await ForgeProjectWorkspace.CreateAsync(projectPath, "Converted assets", new("UYA", "NTSC-U", "1.00", "uya-ntsc-u"),
                new("UYA", "NTSC-U", "1.00", 3, new string('a', 32)), []);
            await UyaStaticLayerStore.WriteSourceAsync(projectPath, new("UYA", "NTSC-U", "1.00", 3, new string('a', 32)),
            [
                new(BakeLayerId.Ties, UyaTieInstancesReader.RecordSize, [0, 0, 0], []),
                new(BakeLayerId.Shrubs, UyaShrubInstancesReader.RecordSize, [0, 0, 0], []),
                new(BakeLayerId.Mobys, UyaMobyInstancesReader.RecordSize, [0, 0, 0], []),
            ]);
            await using (var runtime = new EditorRuntime(placementResolver: UyaAssetPlacementService.CreateAsync))
            {
                await runtime.OpenAsync(projectPath, catalog.RootPath, TimeSpan.Zero);
                foreach (var entry in sources)
                {
                    var page = await QueryAsync(catalog.RootPath, entry);
                    Check(page.Items.Single().CanPlace, $"{entry.Kind} conversion is draggable");
                    var placed = await runtime.ExecuteAsync(Place(entry));
                    var entity = placed.Entities.Single(value => value.EntityId == placed.Selection.Single());
                    Check(entity.SourceClassId == 0x1234
                        && entity.Asset!.Id == entry.Id, "converted class and source identity");
                    Check(!entity.State.MissingAsset, "converted source is resolved");
                    await runtime.ExecuteAsync(new(Guid.NewGuid().ToString("D"), EditorCommandKind.Undo, []));
                    Check(await runtime.ReadWorkspaceAsync(projectPath, (workspace, _) => Task.FromResult(
                        !workspace.Content.CustomClasses.Allocations.Any(value => value.Asset.Id == entry.Id)
                        && !workspace.Content.AssetOverrides.Any(value => value.Source.Id == entry.Id)), default), "undo restores conversion metadata");
                    await runtime.ExecuteAsync(new(Guid.NewGuid().ToString("D"), EditorCommandKind.Redo, []));
                    await runtime.ExecuteAsync(Place(entry));
                }
                Check(await runtime.ReadWorkspaceAsync(projectPath, (workspace, _) => Task.FromResult(
                    workspace.Content.CustomClasses.Allocations.Count == 3 && workspace.Content.AssetOverrides.Count == 3), default),
                    "repeated drops reuse conversions and classes");
                var before = await runtime.ReadWorkspaceAsync(projectPath, (workspace, _) => Task.FromResult(workspace.CurrentFingerprint), default);
                var broken = await catalog.PutAsync(AssetKind.Tie, 1,
                    CatalogModelCodec.Encode(GameId.GC, new byte[0x20], [1], []), Metadata(AssetKind.Tie));
                try { await runtime.ExecuteAsync(Place(broken)); throw new Exception("Expected conversion rejection"); }
                catch (InvalidDataException) { }
                Check(await runtime.ReadWorkspaceAsync(projectPath, (workspace, _) => Task.FromResult(workspace.CurrentFingerprint), default) == before, "failed conversion preserves project state");
                await runtime.SaveAsync();
            }
            var reopened = await ForgeProjectWorkspace.OpenAsync(projectPath);
            Check(reopened.Content.Entities.Count == 6 && reopened.Content.CustomClasses.Allocations.Count == 3, "save/reopen placement");
            foreach (var source in sources)
            {
                var resolved = reopened.ResolveAsset(new(source.Id, source.Kind), catalog)!;
                Check(resolved.ProjectAttached && resolved.Effective.Id != source.Id, "native converted attachment");
                var bytes = await File.ReadAllBytesAsync(resolved.Path);
                Check(CatalogModelCodec.Decode(bytes).Game == GameId.UYA, "UYA native canonical envelope");
                Check(reopened.Content.Assets.Single(value => value.Id == resolved.Effective.Id).ParentId == source.Id,
                    "converted attachment retains source ancestry");
            }
            var inputs = await UyaStaticLayerStore.CreateBakeInputsAsync(reopened, catalog, default);
            Check(inputs.All(input => input.Blockers?.Count is null or 0), "converted static layers can bake: "
                + string.Join("; ", inputs.SelectMany(input => input.Blockers ?? [])));
            Check(inputs.All(input => input.AssetIds.Count == 2), "bake fingerprints include source and converted blobs");
            var plan = BakeLayerGraph.CreatePlan(new(reopened.Manifest.Target, "test", "test"), inputs);
            var staging = await BakeStagingStore.OpenAsync(projectPath);
            foreach (var layer in UyaStaticLayerSchema.Layers)
                await UyaStaticLayerStore.StageAsync(reopened, catalog, staging, plan.Layers.Single(value => value.Layer == layer), default);
            var inventory = await UyaTextureInventoryService.BuildAsync(reopened, catalog, default);
            Check(inventory.Textures.Count == 1, "split GC tie textures enter the texture inventory");
            await VerifyPreviousConversionsAsync(reopened);
            await VerifyVariantReplacementAsync(root, catalog, sources);
        }
        finally { if (Directory.Exists(root)) Directory.Delete(root, recursive: true); }
    }

    private static async Task VerifyVariantReplacementAsync(string root, AssetCatalogStore catalog,
        IReadOnlyList<AssetCatalogEntry> sources)
    {
        foreach (var source in sources.Where(value => value.Kind is AssetKind.Tie or AssetKind.Shrub))
        {
            var path = Path.Combine(root, "variants-" + source.Kind);
            await ForgeProjectWorkspace.CreateAsync(path, "Variant replacement", new("UYA", "NTSC-U", "1.00", "uya-ntsc-u"),
                new("UYA", "NTSC-U", "1.00", 3, new string('a', 32)), []);
            var model = CatalogModelCodec.Decode(await File.ReadAllBytesAsync(catalog.ResolveBlobPath(source.Id)!));
            model.ModelBytes[0x4c] ^= 1;
            var variant = await catalog.PutAsync(source.Kind, 1,
                CatalogModelCodec.Encode(GameId.GC, model.DefinitionBytes, model.ModelBytes, model.Textures), Metadata(source.Kind));
            await using var runtime = new EditorRuntime(placementResolver: UyaAssetPlacementService.CreateAsync);
            await runtime.OpenAsync(path, catalog.RootPath, TimeSpan.Zero);
            var placed = await runtime.ExecuteAsync(Place(source));
            var id = placed.Selection.Single();
            var fingerprint = await runtime.ReadWorkspaceAsync(path, (workspace, _) => Task.FromResult(workspace.CurrentFingerprint), default);
            try { await runtime.ExecuteAsync(Place(variant)); throw new Exception("Expected active-variant conflict"); }
            catch (InvalidDataException) { }
            Check(await runtime.ReadWorkspaceAsync(path, (workspace, _) => Task.FromResult(workspace.CurrentFingerprint), default) == fingerprint,
                "active variant conflicts preserve project state");
            await runtime.ExecuteAsync(new(Guid.NewGuid().ToString("D"), EditorCommandKind.DeleteEntities, [id]));
            await runtime.ExecuteAsync(Place(variant));
            Check(await runtime.ReadWorkspaceAsync(path, (workspace, _) => Task.FromResult(
                workspace.Content.CustomClasses.Allocations.Single().Asset.Id == variant.Id), default),
                "deleting all instances allows another GC variant to reuse the source class");
            await runtime.ExecuteAsync(new(Guid.NewGuid().ToString("D"), EditorCommandKind.Undo, []));
            Check(await runtime.ReadWorkspaceAsync(path, (workspace, _) => Task.FromResult(
                workspace.Content.Entities.Count == 0 && workspace.Content.CustomClasses.Allocations.Single().Asset.Id == source.Id), default),
                "undo restores the previous variant allocation");
            await runtime.ExecuteAsync(new(Guid.NewGuid().ToString("D"), EditorCommandKind.Undo, []));
            Check((await runtime.GetSnapshotAsync()).Entities.Any(value => value.EntityId == id), "undo restores deleted instances");
            await runtime.ExecuteAsync(new(Guid.NewGuid().ToString("D"), EditorCommandKind.Redo, []));
            await runtime.ExecuteAsync(new(Guid.NewGuid().ToString("D"), EditorCommandKind.Redo, []));
            await runtime.SaveAsync();
            var reopened = await ForgeProjectWorkspace.OpenAsync(path);
            Check(reopened.Content.CustomClasses.Allocations.Single().Asset.Id == variant.Id, "replacement survives save/reopen");
            // A native instance may lack a resolved asset while still reserving its class ID.
            var replacementEntity = reopened.Content.Entities.Single();
            var nativeContent = reopened.Content with
            {
                CustomClasses = ProjectCustomClassRegistry.Empty,
                Entities = [replacementEntity with { Asset = null }],
            };
            await reopened.CommitAssetsAsync(nativeContent, [], default);
            var before = reopened.CurrentFingerprint;
            try
            {
                await UyaAssetPlacementService.CreateAsync(reopened, catalog.RootPath,
                    new(source.Id, source.Kind, 0x1234, ProjectTransform.Identity), default);
                throw new Exception("Expected unresolved native-class conflict");
            }
            catch (InvalidDataException) { }
            Check(reopened.CurrentFingerprint == before, "unresolved native classes block GC allocation without changing state");
        }
    }

    private static async Task VerifyPreviousConversionsAsync(ForgeProjectWorkspace workspace)
    {
        var content = workspace.Content;
        var attachments = new ProjectAssetAttachmentCollector();
        foreach (var allocation in content.CustomClasses.Allocations.Where(value =>
            value.Asset.Kind is AssetKind.Tie or AssetKind.Shrub))
        {
            var kind = allocation.Asset.Kind == AssetKind.Tie ? FrontendAssetKind.Tie : FrontendAssetKind.Shrub;
            var source = CatalogModelCodec.Decode(await workspace.ReadAttachedAssetVerifiedAsync(
                allocation.Asset, ForgeProjectWorkspace.MaxAttachedAssetBytes, default));
            var model = source.ModelBytes.ToArray();
            BinaryPrimitives.WriteUInt16LittleEndian(model.AsSpan(kind == FrontendAssetKind.Tie ? 0x44 : 0x24), 0x9009);
            var replacement = attachments.Attach(allocation.Asset.Kind, UyaAssetImportService.CanonicalFormatVersion,
                UyaCanonicalAssetCodec.Encode(source.DefinitionBytes, model, source.Textures), allocation.Asset.Id);
            content = content with
            {
                CustomClasses = content.CustomClasses with { Allocations = content.CustomClasses.Allocations.Select(value =>
                    value.Asset == allocation.Asset ? value with { ClassId = 0x9009 } : value).ToArray() },
                AssetOverrides = content.AssetOverrides.Select(value => value.Source == allocation.Asset
                    ? value with { Replacement = replacement } : value).ToArray(),
                Entities = content.Entities.Select(value => value.Asset != allocation.Asset ? value : value with
                {
                    Source = value.Source! with { ClassId = 0x9009, RawRecord = GameplayInstanceConverter.RebaseStaticClass(
                        GameId.UYA, kind, value.Source.RawRecord, allocation.ClassId, 0x9009) },
                }).ToArray(),
            };
        }
        await workspace.CommitAssetsAsync(content, attachments.Attachments, default);
        var before = workspace.CurrentFingerprint;
        using var cancellation = new CancellationTokenSource();
        cancellation.Cancel();
        try
        {
            await UyaConvertedStaticAssetRepairService.HydrateAsync(workspace, cancellation.Token);
            throw new Exception("Expected repair cancellation");
        }
        catch (OperationCanceledException) { }
        Check(workspace.CurrentFingerprint == before, "cancelled repair preserves project state");
        var allocated = workspace.Content;
        var conflicts = allocated.Entities.Where(value => value.Asset?.Kind is AssetKind.Tie or AssetKind.Shrub)
            .GroupBy(value => value.Asset!.Kind).Select(group => group.First()).Select(value => value with
            {
                EntityId = EntityId.New(), Asset = null,
                Source = value.Source! with { ClassId = 0x1234, RawRecord = GameplayInstanceConverter.RebaseStaticClass(
                    GameId.UYA, value.Asset!.Kind == AssetKind.Tie ? FrontendAssetKind.Tie : FrontendAssetKind.Shrub,
                    value.Source.RawRecord, 0x9009, 0x1234) },
            }).ToArray();
        await workspace.CommitAssetsAsync(allocated with { Entities = allocated.Entities.Concat(conflicts).ToArray() }, [], default);
        var conflictingFingerprint = workspace.CurrentFingerprint;
        Check((await UyaConvertedStaticAssetRepairService.HydrateAsync(workspace, default))?.Severity == EditorDiagnosticSeverity.Warning
            && workspace.CurrentFingerprint == conflictingFingerprint, "class conflicts warn and preserve existing state");
        await workspace.CommitAssetsAsync(allocated, [], default);
        var diagnostic = await UyaConvertedStaticAssetRepairService.HydrateAsync(workspace, default);
        Check(diagnostic?.Severity == EditorDiagnosticSeverity.Info, "previous GC conversions are repaired");
        Check(workspace.Content.CustomClasses.Allocations.All(value => value.ClassId == 0x1234)
            && workspace.Content.Entities.All(value => value.Source?.ClassId == 0x1234),
            "repair restores source class IDs in allocations and instances");
        var tieAllocation = workspace.Content.CustomClasses.Allocations.Single(value => value.Asset.Kind == AssetKind.Tie);
        var native = UyaCanonicalAssetCodec.Decode(await workspace.ReadAttachedAssetVerifiedAsync(
            workspace.ResolveAssetReference(tieAllocation.Asset), ForgeProjectWorkspace.MaxAttachedAssetBytes, default));
        Check(TieClassReader.Read(native.ModelBytes, TieClassReadOptions.ForGameProfile(TieGameProfile.ForGame(GameId.UYA)))
            .LodTopologies[0].StripCount == 3, "repair splits the previously copied folded strip");
        foreach (var entity in workspace.Content.Entities.Where(value => value.Asset?.Kind is AssetKind.Tie or AssetKind.Shrub))
        {
            var previous = content.Entities.Single(value => value.EntityId == entity.EntityId).Source!.RawRecord;
            Check(entity.Source!.RawRecord.AsSpan(4).SequenceEqual(previous.AsSpan(4)),
                "class repair preserves transform, lighting and opaque instance data");
            Check(BinaryPrimitives.ReadInt32LittleEndian(entity.Source.RawRecord) == 0x1234,
                "native instance class is restored");
        }
        Check(await UyaConvertedStaticAssetRepairService.HydrateAsync(workspace, default) is null,
            "conversion repair is idempotent");
        await workspace.SaveAsync();
        var reopened = await ForgeProjectWorkspace.OpenAsync(workspace.RootPath);
        Check(reopened.Content.CustomClasses.Allocations.All(value => value.ClassId == 0x1234),
            "repaired native class allocations survive save/reopen");
    }

    private static EditorCommand Place(AssetCatalogEntry entry) => new(Guid.NewGuid().ToString("D"),
        EditorCommandKind.CreateEntityFromAsset, [], Placement: new(entry.Id, entry.Kind, 0x1234, ProjectTransform.Identity, AssetSourceSelection.From(entry.Sources[0])));

    private static AssetImportMetadata Metadata(AssetKind kind) => new("conversion-test",
        new("GC", "NTSC-U", "1.01", "level01", "assets/asset_wad.bin", 0, new string('b', 32)),
        [$"{kind.ToString().ToLowerInvariant()}:0x1234"], ["vanilla", "game:GC"]);

    private static async Task<AssetExplorerPagePayload> QueryAsync(string root, AssetCatalogEntry entry)
    {
        var category = entry.Kind switch
        {
            AssetKind.Tie => AssetExplorerCategoryPayload.Ties,
            AssetKind.Shrub => AssetExplorerCategoryPayload.Shrubs,
            _ => AssetExplorerCategoryPayload.Mobys,
        };
        var request = new AssetExplorerRequestPayload(root, category, entry.Id.ToString(), null, null, null, null,
            [], null, 64, "UYA", "NTSC-U", "1.00", 0);
        return AssetExplorerPayloadCodec.DecodePage(await ProjectBridgeHandlers.HandleAsync(
            new(BridgeMessageKind.Request, BridgeOpcode.QueryAssetExplorer, BridgeErrorCode.None, 1,
                AssetExplorerPayloadCodec.EncodeRequest(request)), "test-sdk", _ => ValueTask.CompletedTask, default));
    }

    private static void Check(bool condition, string message) { if (!condition) throw new Exception(message); }
}
